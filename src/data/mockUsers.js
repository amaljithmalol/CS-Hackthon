export function hashPassword(password, salt = 'foodbridge') {
  let hash = 5381
  const input = `${salt}::${password}::${salt}`
  for (let i = 0; i < input.length; i += 1) {
    hash = (hash * 33) ^ input.charCodeAt(i)
  }
  let out = ''
  let n = Math.abs(hash)
  while (n > 0) {
    out += (n % 36).toString(36)
    n = Math.floor(n / 36)
  }
  return `fb$${salt}$${out.padStart(6, '0')}`
}

